"""Generate CSS variables consumed by the frontend."""

from pathlib import Path

from palette import NEUTRALS, PALETTES, audit, palette

if audit():
    raise SystemExit("Palette contrast audit failed")

lines = ["/* Generated by design/build_tokens.py; do not edit. */"]
for theme in PALETTES:
    for mode in NEUTRALS:
        selector = f':root[data-theme="{theme}"][data-mode="{mode}"]'
        lines.append(selector + " {")
        lines.extend(f"  --{name.replace('_', '-')}: {value};" for name, value in palette(theme, mode).items())
        lines.append("}")
target = Path(__file__).with_name("tokens.css")
target.write_text("\n".join(lines) + "\n", encoding="utf-8")
print(f"Generated {target} with {len(PALETTES) * len(NEUTRALS)} palettes")
