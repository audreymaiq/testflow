"""Generate CSS variables consumed by the frontend."""

from pathlib import Path

from palette import NEUTRALS, audit, palette

if audit():
    raise SystemExit("Palette contrast audit failed")

lines = ["/* Generated by design/build_tokens.py; do not edit. */"]
for mode in NEUTRALS:
    selector = f':root[data-mode="{mode}"]'
    lines.append(selector + " {")
    lines.extend(f"  --{name.replace('_', '-')}: {value};" for name, value in palette(mode).items())
    lines.append("}")
target = Path(__file__).with_name("tokens.css")
target.write_text("\n".join(lines) + "\n", encoding="utf-8")
print(f"Generated {target} with {len(NEUTRALS)} color modes")
