  const content = `#TITLE: Bản nháp ${suffix}\n#SUBJECT: toan\n#LEVEL: THPT\n#GRADE: 12\n#TYPE: ON_TAP\n[CH1] Số học\nHai cộng hai?\nA. Ba\nB. Bốn\n=>B\n`
